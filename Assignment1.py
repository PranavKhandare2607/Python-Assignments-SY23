# Taking input from the user
n1 = int(input("Enter 1st Digit: "))
n2 = int(input("Enter 2nd Digit: "))


# Simple Calculations
print("\nSimple Calculations:\n")


# Addition
n3 = n2 + n1
print("Addition is:", n3)


# Subtraction
n3 = n2 - n1
print("Subtraction is:", n3)


# Multiplication
n3 = n2 * n1
print("Multiplication is:", n3)


# Advanced Calculations
print("\nAdvanced Calculations:\n")


# Modulus
n3 = n1 % n2
print("The Modulus is:", n3)


# Exponentiation
n3 = n1 ** n2
print("The Exponential value is:", n3)


# Floor Division
n3 = n1 // n2
print("The Floor Division is:", n3)
